/**
 * Единое разрешение отрисовки (device-пикселей на CSS-пиксель), общее для движка
 * рендера и атласа шрифтов.
 *
 * Текст рисуется как pixi `BitmapText` из заранее сглаженного атласа глифов, поэтому
 * для чёткости должны одновременно выполняться два условия:
 *
 * 1. Атлас глифов должен иметь ТО ЖЕ разрешение, что и рендерер. Если атлас плотнее
 *    (что давала прежняя формула `renderResolution * 2`), глиф уменьшается при
 *    отрисовке (2:1 минификация с linear+mipmap) и мылится; если реже — растягивается.
 *    Это НЕ бесплатный супер-сэмплинг: супер-сэмплить нужно сцену, а не текстуру шрифта.
 *
 * 2. Сцена должна рендериться минимум в 2x (супер-сэмплинг) даже при целом DPI.
 *    Pixi располагает каждый глиф на дробной субпиксельной позиции
 *    (`advance * fontSize / 100`), а `roundPixels` снэпит только начало строки, не
 *    отдельные глифы. При 1x уже сглаженный глиф ресемплится мимо пиксельной сетки и
 *    мылит (хуже для мелкого шрифта и при уменьшении размера). Рендер в 2x с
 *    последующим уменьшением браузером даёт чёткость нативного canvas `fillText`.
 *
 * Значения подтверждены замером живого виджета: при dpr=1 связка рендерер=1/атлас=2
 * (прежнее поведение) мылит, рендерер=2/атлас=2 — чёткая.
 */

/** Нижняя граница: супер-сэмплинг, скрывающий субпиксельное положение глифов. */
const MIN_RENDER_RESOLUTION = 2;

/** Верхняя граница: ограничивает стоимость заливки (общий рендерер тянет 100+ виджетов). */
const MAX_RENDER_RESOLUTION = 2;

/**
 * Целое разрешение отрисовки: не ниже dpr (на дробном DPI канва попадает на физическую
 * пиксельную сетку), но в пределах [MIN, MAX] для чёткости текста и контроля стоимости.
 */
export function getRenderResolution(): number {
  const dpr = globalThis.devicePixelRatio;
  const dipScale = Math.ceil(dpr > 0 ? dpr : 1);
  return Math.min(Math.max(dipScale, MIN_RENDER_RESOLUTION), MAX_RENDER_RESOLUTION);
}
